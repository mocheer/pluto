package gen

import (
	"bytes"
	"log"

	"github.com/dave/jennifer/jen"
)

type generator struct {
	jen.File
}

func Package(name string) *generator {
	f := jen.NewFile(name)
	f.Comment("Code generated by gen. DO NOT EDIT.")
	return &generator{
		File: *f,
	}
}

// AddVar
// m.AddVar("a", jen.Lit("string value")) => var a = "string value"
// m.AddVar("b", jen.Lit(5))  => var b = 5
func (m *generator) AddVar(name string, value *jen.Statement) *generator {
	m.Var().Id(name).Op("=").Add(value)
	return m
}

// AddVarLit
func (m *generator) AddVarLit(name string, v any) *generator {
	m.AddVar(name, jen.Lit(v))
	return m
}

// AddMethod
func (m *generator) AddMethod(name string) *generator {
	m.Func().Id(name)
	return m
}

// TypeStruct
func (m *generator) TypeStruct(ss *StructSchema) *generator {
	m.Add(ss.Type())
	return m
}

// Buffer 输出Buffer
func (m *generator) Buffer() *bytes.Buffer {
	buf := &bytes.Buffer{}
	err := m.Render(buf)
	if err != nil {
		log.Println(err.Error())
	}
	return buf
}

// String 输出String
func (m *generator) String() string {
	return m.Buffer().String()
}
