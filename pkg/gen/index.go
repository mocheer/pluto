package gen

import (
	"bytes"
	"log"

	"github.com/dave/jennifer/jen"
)

type generator jen.File

func Package(name string) *generator {
	f := jen.NewFile("dao")
	f.Comment("Code generated by gen. DO NOT EDIT.")
	g := generator(*f)
	return &g
}

// AddVar
// m.AddVar("a", jen.Lit("string value")) => var a = "string value"
// m.AddVar("b", jen.Lit(5))  => var b = 5
func (m *generator) AddVar(name string, value *jen.Statement) *jen.Statement {
	return m.Var().Id(name).Op("=").Add(value)
}

// AddMethod
func (m *generator) AddMethod(name string) *jen.Statement {
	return m.Func().Id(name)
}

func (m *generator) Buffer() *bytes.Buffer {
	buf := &bytes.Buffer{}
	err := m.Render(buf)
	if err != nil {
		log.Println(err.Error())
	}
	return buf
}

func (m *generator) String() string {
	return m.Buffer().String()
}
